export type Difficulty = 'easy' | 'medium' | 'hard';

interface Base {
  id: string;
  title: string;
  pattern: PatternId;
  companies: CompanyId[];
  difficulty: Difficulty;
}

/**
 * Syntax drill. In `code`, write __0__, __1__ ... where a blank goes.
 * Each blank lists accepted answers. An answer starting with "re:" is a
 * regex tested against the whitespace-stripped input.
 */
export interface SyntaxExercise extends Base {
  kind: 'syntax';
  prompt: string;
  code: string;
  blanks: { answers: string[]; intent: string }[];
  note?: string;
}

/** Bug hunt. `line` is 1-indexed. options[0] is the correct fix. */
export interface BugExercise extends Base {
  kind: 'bug';
  prompt: string;
  code: string;
  bugs: { line: number; options: string[]; explanation: string }[];
}

/** Pattern finder: read a full problem, pick the pattern for the optimal solution. */
export interface PatternExercise extends Base {
  kind: 'pattern';
  statement: string;
  example: string;
  constraints: string;
  answer: string; // FINDER_PATTERNS id
  answerPattern: PatternId; // for the pattern filter
  confusers: string[]; // tempting wrong answers, shown as options first
  clue: string; // the words in the problem that give it away
  brute: string; // the obvious approach and why it is too slow
  insight: string; // how the pattern solves it
  optimal: string; // complexity of the pattern solution
  whyNot?: Record<string, string>; // specific reason a tempting option fails
  followUp?: string; // what interviewers ask next
  nc?: string; // NeetCode slug
}

export type Exercise = SyntaxExercise | BugExercise | PatternExercise;
export type Mode = 'practical' | 'lab' | 'blueprint' | 'coach' | 'roadmap' | 'oa' | 'path' | 'learn' | 'dashboard' | 'syntax' | 'bug' | 'pattern' | 'cards' | 'design' | 'companies' | 'reference';

export interface CardState {
  reps: number;
  ease: number;
  interval: number; // days
  due: number; // epoch ms
  attempts: number;
  correct: number;
  lastResult: boolean | null;
  lastSeen: number;
}

export interface Progress {
  cards: Record<string, CardState>;
  days: string[]; // YYYY-MM-DD dates with practice
  mistakes: Record<string, number>; // diagnostic tag -> count
  math: { at: number; score: number }[]; // mental math round results
  savedAt?: number; // last local change, used to merge with the cloud copy
  lessons?: Record<string, LessonState>; // pattern lessons: opened + quick check results
}

export interface LessonState { opened?: number; checks?: Record<number, boolean>; learned?: boolean }

/** Mock online assessment problem (generated by scripts/oa_problems.py). */
export interface OAProblem {
  id: string;
  kind: 'debug' | 'code' | 'build';
  title: string;
  func: string; // function name, or class name for builds
  statement: string;
  starter: string;
  solution: string;
  tests: unknown[]; // args per test, or [method, args] call lists for builds
  expected: unknown[];
  visible: number; // first N tests are shown and used by Run
  cmp: 'exact' | 'unordered';
  explain: string;
  difficulty: 'easy' | 'medium' | 'hard';
  tags?: string[];
}

